#!/usr/bin/env python3
"""Generates localization files from tools/strings.json.

- Shared/L10nTables.swift      in-app tables (ru, uz, uz-Cyrl, en)
- ZIKR/<lang>.lproj/*.strings  system-facing strings (App Intents, Info.plist, App Shortcuts)
- ZIKRWidgets/<lang>.lproj/Localizable.strings

Uzbek Cyrillic is transliterated from Uzbek Latin, so only ru/uz/en are written by hand.
Usage: python3 tools/gen_l10n.py [--check]   (--check verifies every key used in code exists)
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools" / "strings.json"

PROTECTED = [
    r"%\d\$@", r"%@", r"\$\{applicationName\}", "ZIKR", "iPhone", "iPad", "iCloud", "App Store",
    "Apple Watch", "Dynamic Island", "Live Activity", "OLED", "Face ID", "Siri",
]

SINGLE = {
    "a": "а", "b": "б", "d": "д", "e": "е", "f": "ф", "g": "г", "h": "ҳ", "i": "и", "j": "ж",
    "k": "к", "l": "л", "m": "м", "n": "н", "o": "о", "p": "п", "q": "қ", "r": "р", "s": "с",
    "t": "т", "u": "у", "v": "в", "x": "х", "y": "й", "z": "з", "c": "с", "w": "в",
}
APOS_OG = "‘ʻ'`"          # o‘ / g‘ markers
APOS_TUTUQ = "’ʼ"         # tutuq belgisi -> ъ
VOWELS = set("aeiouAEIOU")


def _case(src: str, dst: str) -> str:
    return dst.upper() if src[:1].isupper() else dst


def translit_word(text: str) -> str:
    out = []
    i = 0
    n = len(text)
    while i < n:
        ch = text[i]
        low = ch.lower()
        nxt = text[i + 1] if i + 1 < n else ""
        nxt2 = text[i + 2] if i + 2 < n else ""
        prev = text[i - 1] if i > 0 else ""
        word_start = prev == "" or (not prev.isalpha() and prev not in APOS_OG + APOS_TUTUQ)
        if low in ("o", "g") and nxt in APOS_OG:
            out.append(_case(ch, "ў" if low == "o" else "ғ"))
            i += 2
            continue
        if low == "s" and nxt.lower() == "h":
            out.append(_case(ch, "ш")); i += 2; continue
        if low == "c" and nxt.lower() == "h":
            out.append(_case(ch, "ч")); i += 2; continue
        if low == "y" and nxt and nxt.lower() in "oaue" and not (nxt.lower() == "o" and nxt2 in APOS_OG):
            mapping = {"o": "ё", "a": "я", "u": "ю", "e": "е"}
            out.append(_case(ch, mapping[nxt.lower()])); i += 2; continue
        if low == "e" and (word_start or prev.lower() in VOWELS):
            out.append(_case(ch, "э")); i += 1; continue
        if ch in APOS_TUTUQ:
            # After a protected Latin word (iPhone’da) keep the apostrophe; inside a word it is ъ.
            out.append("’" if i == 0 else "ъ"); i += 1; continue
        if low in SINGLE:
            out.append(_case(ch, SINGLE[low])); i += 1; continue
        out.append(ch)
        i += 1
    return "".join(out)


def to_cyrillic(text: str) -> str:
    pattern = re.compile("(" + "|".join(PROTECTED) + ")")
    parts = pattern.split(text)
    return "".join(p if pattern.fullmatch(p) else translit_word(p) for p in parts)


def swift_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def strings_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


APP_SHORTCUT_PHRASES = {
    "Add one in ${applicationName}": {"ru": "Плюс один в ${applicationName}", "uz": "${applicationName} da bitta qo‘shish"},
    "Count in ${applicationName}": {"ru": "Считать в ${applicationName}", "uz": "${applicationName} da hisoblash"},
    "${applicationName} plus one": {"ru": "${applicationName} плюс один", "uz": "${applicationName} plyus bir"},
    "Undo in ${applicationName}": {"ru": "Отменить в ${applicationName}", "uz": "${applicationName} da bekor qilish"},
    "Undo last tap in ${applicationName}": {"ru": "Отменить последнее нажатие в ${applicationName}", "uz": "${applicationName} da oxirgi bosishni bekor qilish"},
    "What is my count in ${applicationName}": {"ru": "Какой у меня счёт в ${applicationName}", "uz": "${applicationName} da hisobim qancha"},
    "Current count in ${applicationName}": {"ru": "Текущий счёт в ${applicationName}", "uz": "${applicationName} da joriy hisob"},
}

SYSTEM_PREFIXES = ("intent.", "shortcut.", "control.", "widget.", "entity.")
LANGS = {"en": "en", "ru": "ru", "uz": "uz", "uzCyrl": "uz-Cyrl"}


def build_tables(data):
    tables = {"ru": {}, "uz": {}, "uzCyrl": {}, "en": {}}
    for key, value in data.items():
        for lang in ("ru", "uz", "en"):
            if lang not in value:
                raise SystemExit(f"missing {lang} for {key}")
            tables[lang][key] = value[lang]
        tables["uzCyrl"][key] = to_cyrillic(value["uz"])
    return tables


def write_swift(tables):
    lines = ["// Generated by tools/gen_l10n.py from tools/strings.json. Do not edit.", "",
             "enum L10nTables {"]
    for lang in ("ru", "uz", "uzCyrl", "en"):
        lines.append(f"    static let {lang}: [String: String] = [")
        for key in sorted(tables[lang]):
            if key.startswith("infoplist."):
                continue
            lines.append(f'        "{swift_escape(key)}": "{swift_escape(tables[lang][key])}",')
        lines.append("    ]")
    lines.append("}")
    (ROOT / "Shared" / "L10nTables.swift").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_strings(path: pathlib.Path, pairs):
    path.parent.mkdir(parents=True, exist_ok=True)
    body = "/* Generated by tools/gen_l10n.py. Do not edit. */\n\n"
    body += "".join(f'"{strings_escape(k)}" = "{strings_escape(v)}";\n' for k, v in pairs)
    path.write_text(body, encoding="utf-8")


def write_lproj(tables):
    for lang, folder in LANGS.items():
        system = [(k, v) for k, v in sorted(tables[lang].items()) if k.startswith(SYSTEM_PREFIXES)]
        for target in ("ZIKR", "ZIKRWidgets"):
            write_strings(ROOT / target / f"{folder}.lproj" / "Localizable.strings", system)
        info = [(k.split(".", 1)[1], v) for k, v in tables[lang].items() if k.startswith("infoplist.")]
        write_strings(ROOT / "ZIKR" / f"{folder}.lproj" / "InfoPlist.strings", info)
        write_strings(ROOT / "ZIKRWidgets" / f"{folder}.lproj" / "InfoPlist.strings", info)
        phrases = []
        for en, tr in APP_SHORTCUT_PHRASES.items():
            if lang == "en":
                value = en
            elif lang == "uzCyrl":
                value = to_cyrillic(tr["uz"])
            else:
                value = tr[lang]
            phrases.append((en, value))
        write_strings(ROOT / "ZIKR" / f"{folder}.lproj" / "AppShortcuts.strings", phrases)


def check_keys(data):
    used = set()
    for path in list((ROOT / "Shared").rglob("*.swift")) + list((ROOT / "ZIKR").rglob("*.swift")) + list((ROOT / "ZIKRWidgets").rglob("*.swift")):
        if path.name == "L10nTables.swift":
            continue
        text = path.read_text(encoding="utf-8")
        used |= set(re.findall(r'"([a-z][a-zA-Z0-9]*(?:\.[a-zA-Z0-9]+)+)"', text))
    used |= {f"appearance.{x}" for x in ("system", "light", "dark")}
    prefixes = tuple(k.split(".")[0] + "." for k in data)
    used = {k for k in used if k.startswith(prefixes) and not k.startswith(("zikr.", "group."))}
    missing = sorted(k for k in used if k not in data)
    unused = sorted(k for k in data if k not in used and not k.startswith("infoplist."))
    return missing, unused


def main():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    tables = build_tables(data)
    write_swift(tables)
    write_lproj(tables)
    missing, unused = check_keys(data)
    print(f"{len(data)} keys generated for ru, uz, uz-Cyrl, en")
    if unused:
        print("unused keys:", ", ".join(unused))
    if missing:
        print("MISSING keys used in code:", ", ".join(missing))
        if "--check" in sys.argv:
            sys.exit(1)


if __name__ == "__main__":
    main()
